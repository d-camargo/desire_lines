    def add_action(
            self,
            icon_path,
            text,
            callback,
            enabled_flag=True,
            add_to_menu=True,
            add_to_toolbar=True,
            status_tip=None,
            whats_this=None,
            parent=None,
            checkable=False):
        """Add a toolbar icon to the toolbar.

        :param icon_path: Path to the icon for this action. Can be a resource
            path (e.g. ':/plugins/foo/bar.png') or a normal file system path.
        :type icon_path: str

        :param text: Text that should be shown in menu items for this action.
        :type text: str

        :param callback: Function to be called when the action is triggered.
        :type callback: function

        :param enabled_flag: A flag indicating if the action should be enabled
            by default. Defaults to True.
        :type enabled_flag: bool

        :param add_to_menu: Flag indicating whether the action should also
            be added to the menu. Defaults to True.
        :type add_to_menu: bool

        :param add_to_toolbar: Flag indicating whether the action should also
            be added to the toolbar. Defaults to True.
        :type add_to_toolbar: bool

        :param status_tip: Optional text to show in a popup when mouse pointer
            hovers over the action.
        :type status_tip: str

        :param parent: Parent widget for the new action. Defaults None.
        :type parent: QWidget

        :param whats_this: Optional text to show in the status bar when the
            mouse pointer hovers over the action.

        :param checkable: Flag indicating whether the action should be checkable.

        :returns: The action that was created. Note that the action is also
            added to self.actions list.
        :rtype: QAction
        """

        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        if checkable:
            action.setCheckable(True)

        if status_tip is not None:
            action.setStatusTip(status_tip)

        if whats_this is not None:
            action.setWhatsThis(whats_this)

        if add_to_toolbar:
            # Adds plugin icon to Plugins toolbar
            self.iface.addToolBarIcon(action)

        if add_to_menu:
            self.iface.addPluginToVectorMenu(
                self.menu,
                action)

        self.actions.append(action)

        return action

    def initGui(self):
        """Create the menu entries and toolbar icons inside the QGIS GUI."""

        icon_path = os.path.join(os.path.dirname(__file__), 'icon.png')
        self.main_action = self.add_action(
            icon_path,
            text=self.tr(u'Desire Lines'),
            callback=self.run,
            parent=self.iface.mainWindow(),
            add_to_toolbar=False)

        self.traffic_action = self.add_action(
            icon_path,
            text=self.tr(u'Alocação em rodovias'),
            callback=self.show_traffic_panel,
            parent=self.iface.mainWindow(),
            checkable=True,
            add_to_toolbar=False)

        self.toolbar_menu = QMenu(self.iface.mainWindow())
        self.toolbar_menu.addAction(self.main_action)
        self.toolbar_menu.addAction(self.traffic_action)

        self.toolbar_button = QToolButton(self.iface.mainWindow())
        self.toolbar_button.setMenu(self.toolbar_menu)
        self.toolbar_button.setDefaultAction(self.main_action)
        self.toolbar_button.setPopupMode(QToolButton.ToolButtonPopupMode.MenuButtonPopup)

        self.toolbar_action = self.iface.addToolBarWidget(self.toolbar_button)

        # will be set False in run()
        self.first_start = True

        QTimer.singleShot(0, self._check_gisbr)

    def _check_gisbr(self):
        """Check if GISBR is available and prompt installation if missing (D2).

        :returns: True if the prompt message box was shown, False otherwise.
        :rtype: bool
        """
        settings = QgsSettings()
        if settings.value('desire_lines/skip_gisbr_check', False, type=bool):
            return False

        if gisbr_bridge.is_available():
            return False

        box = QMessageBox(self.iface.mainWindow())
        box.setIcon(QMessageBox.Icon.Information)
        box.setWindowTitle(self.tr(u'Desire Lines — GISBR'))
        extra_phrase = self.tr(u'Other plugin features remain available without it.')
        message = u'{}\n\n{}'.format(gisbr_bridge.missing_message(), extra_phrase)
        box.setText(message)

        btn_manage = box.addButton(
            self.tr(u'Open Plugin Manager'),
            QMessageBox.ButtonRole.AcceptRole
        )
        box.addButton(
            self.tr(u'Not now'),
            QMessageBox.ButtonRole.RejectRole
        )

        cb = QCheckBox(self.tr(u"Don't show again"))
        box.setCheckBox(cb)

        box.exec()
        checked = cb.isChecked()

        if checked:
            settings.setValue('desire_lines/skip_gisbr_check', True)

        if box.clickedButton() == btn_manage:
            action = self.iface.actionManagePlugins()
            if action is not None:
                action.trigger()

        return True

    def show_traffic_panel(self):
        """Show or toggle the Traffic Assignment dock widget."""
        if self.traffic_panel is None:
            self.traffic_panel = TrafficAssignmentPanel(self.iface.mainWindow())
            self.iface.addDockWidget(Qt.DockWidgetArea.RightDockWidgetArea, self.traffic_panel)
            self.traffic_panel.show()
        else:
            if self.traffic_panel.isVisible():
                self.traffic_panel.hide()
            else:
                self.traffic_panel.show()

    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""
        if self.traffic_panel is not None:
            self.iface.removeDockWidget(self.traffic_panel)
            self.traffic_panel.deleteLater()
            self.traffic_panel = None
        for action in self.actions:
            self.iface.removePluginVectorMenu(
                self.tr(u'&Desire Lines'),
                action)
        if self.toolbar_action is not None:
            self.iface.removeToolBarIcon(self.toolbar_action)
            self.toolbar_action = None

